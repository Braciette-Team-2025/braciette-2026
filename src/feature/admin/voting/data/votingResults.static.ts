function slugify(value: string): string {
  return value
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function toItems(type: string, rows: RawRow[]): VotingHomeItem[] {
  return rows.map(([name, votes]) => ({
    id: `${type.toLowerCase()}-${slugify(name)}`,
    type,
    name,
    logo_url: "",
    vote_count: votes,
  }));
}

